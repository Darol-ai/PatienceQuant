def quant_v3_research_universe() -> list[dict]:
    """给API/前端用的整理好的列表——每支股票的分组、行业、研究依据和
    风险点，按 broad_universe.py 里的顺序（和策略实际使用的候选池顺序
    一致）。"""
    rows = []
    for stock in BROAD_STOCKS:
        note = QUANT_V3_STOCK_NOTES.get(stock["symbol"], {"thesis": "", "risk": ""})
        rows.append({
            "symbol": stock["symbol"],
            "name": stock["name"],
            "industry": stock["industry"],
            "group": stock["group"],
            "thesis": note["thesis"],
            "risk": note["risk"],
        })
    return rows
